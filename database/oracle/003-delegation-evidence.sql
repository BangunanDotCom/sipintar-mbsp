CREATE TRIGGER STL_TR_DEL_IMMUTABLE
  BEFORE UPDATE ON STL_DELEGATION_DOCUMENTS FOR EACH ROW
BEGIN
  IF UPDATING('CONTENT')
    OR (:OLD.ID<>:NEW.ID OR (:OLD.ID IS NULL AND :NEW.ID IS NOT NULL) OR (:OLD.ID IS NOT NULL AND :NEW.ID IS NULL))
    OR (:OLD.COMPANY_ID<>:NEW.COMPANY_ID OR (:OLD.COMPANY_ID IS NULL AND :NEW.COMPANY_ID IS NOT NULL) OR (:OLD.COMPANY_ID IS NOT NULL AND :NEW.COMPANY_ID IS NULL))
    OR (:OLD.REPRESENTATIVE_ID<>:NEW.REPRESENTATIVE_ID OR (:OLD.REPRESENTATIVE_ID IS NULL AND :NEW.REPRESENTATIVE_ID IS NOT NULL) OR (:OLD.REPRESENTATIVE_ID IS NOT NULL AND :NEW.REPRESENTATIVE_ID IS NULL))
    OR (:OLD.VERSION<>:NEW.VERSION OR (:OLD.VERSION IS NULL AND :NEW.VERSION IS NOT NULL) OR (:OLD.VERSION IS NOT NULL AND :NEW.VERSION IS NULL))
    OR (:OLD.FILE_NAME<>:NEW.FILE_NAME OR (:OLD.FILE_NAME IS NULL AND :NEW.FILE_NAME IS NOT NULL) OR (:OLD.FILE_NAME IS NOT NULL AND :NEW.FILE_NAME IS NULL))
    OR (:OLD.MIME_TYPE<>:NEW.MIME_TYPE OR (:OLD.MIME_TYPE IS NULL AND :NEW.MIME_TYPE IS NOT NULL) OR (:OLD.MIME_TYPE IS NOT NULL AND :NEW.MIME_TYPE IS NULL))
    OR (:OLD.UPLOADED_BY<>:NEW.UPLOADED_BY OR (:OLD.UPLOADED_BY IS NULL AND :NEW.UPLOADED_BY IS NOT NULL) OR (:OLD.UPLOADED_BY IS NOT NULL AND :NEW.UPLOADED_BY IS NULL))
    OR (:OLD.SHA256<>:NEW.SHA256 OR (:OLD.SHA256 IS NULL AND :NEW.SHA256 IS NOT NULL) OR (:OLD.SHA256 IS NOT NULL AND :NEW.SHA256 IS NULL))
    OR (:OLD.BYTE_SIZE<>:NEW.BYTE_SIZE OR (:OLD.BYTE_SIZE IS NULL AND :NEW.BYTE_SIZE IS NOT NULL) OR (:OLD.BYTE_SIZE IS NOT NULL AND :NEW.BYTE_SIZE IS NULL))
    OR (:OLD.AUTHORITY_TYPE<>:NEW.AUTHORITY_TYPE OR (:OLD.AUTHORITY_TYPE IS NULL AND :NEW.AUTHORITY_TYPE IS NOT NULL) OR (:OLD.AUTHORITY_TYPE IS NOT NULL AND :NEW.AUTHORITY_TYPE IS NULL))
    OR (:OLD.VALID_FROM<>:NEW.VALID_FROM OR (:OLD.VALID_FROM IS NULL AND :NEW.VALID_FROM IS NOT NULL) OR (:OLD.VALID_FROM IS NOT NULL AND :NEW.VALID_FROM IS NULL))
    OR (:OLD.VALID_UNTIL<>:NEW.VALID_UNTIL OR (:OLD.VALID_UNTIL IS NULL AND :NEW.VALID_UNTIL IS NOT NULL) OR (:OLD.VALID_UNTIL IS NOT NULL AND :NEW.VALID_UNTIL IS NULL))
    OR (:OLD.CREATED_AT<>:NEW.CREATED_AT OR (:OLD.CREATED_AT IS NULL AND :NEW.CREATED_AT IS NOT NULL) OR (:OLD.CREATED_AT IS NOT NULL AND :NEW.CREATED_AT IS NULL))
    OR (:OLD.SUPERSEDED_AT IS NOT NULL AND (:OLD.SUPERSEDED_AT<>:NEW.SUPERSEDED_AT OR (:OLD.SUPERSEDED_AT IS NULL AND :NEW.SUPERSEDED_AT IS NOT NULL) OR (:OLD.SUPERSEDED_AT IS NOT NULL AND :NEW.SUPERSEDED_AT IS NULL)))
    OR (:OLD.REVOKED_AT IS NOT NULL AND (:OLD.REVOKED_AT<>:NEW.REVOKED_AT OR (:OLD.REVOKED_AT IS NULL AND :NEW.REVOKED_AT IS NOT NULL) OR (:OLD.REVOKED_AT IS NOT NULL AND :NEW.REVOKED_AT IS NULL)))
  THEN
    RAISE_APPLICATION_ERROR(-20003,'Delegation identity and withdrawal are immutable');
  END IF;
END;
