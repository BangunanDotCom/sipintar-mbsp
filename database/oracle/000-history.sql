CREATE TABLE STL_SCHEMA_MIGRATIONS (
  VERSION VARCHAR2(64 CHAR) CONSTRAINT STL_HIST_VERSION_NN NOT NULL,
  CHECKSUM VARCHAR2(64 CHAR) CONSTRAINT STL_HIST_CHECKSUM_NN NOT NULL,
  STATE VARCHAR2(16 CHAR) CONSTRAINT STL_HIST_STATE_NN NOT NULL,
  STARTED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP CONSTRAINT STL_HIST_START_NN NOT NULL,
  APPLIED_AT TIMESTAMP(6) WITH TIME ZONE,
  CONSTRAINT STL_HIST_PK PRIMARY KEY (VERSION),
  CONSTRAINT STL_HIST_STATE_CK CHECK (STATE IN ('APPLYING','APPLIED'))
)
