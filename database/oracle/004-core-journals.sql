CREATE TABLE STL_TRAINING_REMINDER_OUTBOX (
 ID VARCHAR2(128 CHAR) CONSTRAINT STL_PK_TRAIN_REM PRIMARY KEY,
 DRAFT_ID VARCHAR2(128 CHAR) CONSTRAINT STL_NN_TR_DRAFT NOT NULL,
 DRAFT_VERSION NUMBER(10) CONSTRAINT STL_NN_TR_VERSION NOT NULL,
 RECIPIENT_ID VARCHAR2(128 CHAR) CONSTRAINT STL_NN_TR_RECIPIENT NOT NULL,
 SOURCE VARCHAR2(16 CHAR) CONSTRAINT STL_NN_TR_SOURCE NOT NULL,
 STATUS VARCHAR2(16 CHAR) DEFAULT 'PENDING' CONSTRAINT STL_NN_TR_STATUS NOT NULL,
 ATTEMPTS NUMBER(2) DEFAULT 0 CONSTRAINT STL_NN_TR_ATTEMPTS NOT NULL,
 AVAILABLE_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP CONSTRAINT STL_NN_TR_AVAILABLE NOT NULL,
 LEASE_UNTIL TIMESTAMP(6) WITH TIME ZONE,
 LAST_ERROR VARCHAR2(64 CHAR),
 CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP CONSTRAINT STL_NN_TR_CREATED NOT NULL,
 SENT_AT TIMESTAMP(6) WITH TIME ZONE,
 KIND VARCHAR2(16 CHAR) DEFAULT 'DRAFT_INACTIVE' CONSTRAINT STL_NN_TR_KIND NOT NULL,
 CONTEXT CLOB,
 DEDUPE_KEY VARCHAR2(256 CHAR) CONSTRAINT STL_NN_TR_DEDUPE NOT NULL,
 NOTIFIED_AT TIMESTAMP(6) WITH TIME ZONE,
 CONSTRAINT STL_UK_TR_DEDUPE UNIQUE (DEDUPE_KEY),
 CONSTRAINT STL_FK_TR_DRAFT FOREIGN KEY (DRAFT_ID) REFERENCES STL_APPLICATION_DRAFTS (ID),
 CONSTRAINT STL_FK_TR_USER FOREIGN KEY (RECIPIENT_ID) REFERENCES STL_USERS (ID),
 CONSTRAINT STL_CK_TR_VERSION CHECK (DRAFT_VERSION>0),
 CONSTRAINT STL_CK_TR_SOURCE CHECK (SOURCE IN ('SUPERVISOR','SCHEDULE')),
 CONSTRAINT STL_CK_TR_STATUS CHECK (STATUS IN ('PENDING','SENDING','SENT','FAILED','CANCELLED','UNCERTAIN')),
 CONSTRAINT STL_CK_TR_ATTEMPTS CHECK (ATTEMPTS BETWEEN 0 AND 5),
 CONSTRAINT STL_CK_TR_KIND CHECK (KIND IN ('DRAFT_INACTIVE','TECH_PRE_DUE','TECH_OVERDUE','TECH_ESCALATE')),
 CONSTRAINT STL_CK_TR_CONTEXT CHECK ((KIND='DRAFT_INACTIVE' AND CONTEXT IS NULL) OR (KIND<>'DRAFT_INACTIVE' AND CONTEXT IS NOT NULL)),
 CONSTRAINT STL_CK_TR_JSON CHECK (CONTEXT IS JSON)
) LOB (CONTEXT) STORE AS BASICFILE STL_LOB_TR_CONTEXT
-- @statement
CREATE INDEX STL_IX_TR_DUE ON STL_TRAINING_REMINDER_OUTBOX (STATUS, AVAILABLE_AT)
-- @statement
CREATE TABLE STL_SYNTH_FINANCIAL_ENTRIES (
 ID VARCHAR2(128 CHAR) CONSTRAINT STL_PK_SYN_FIN PRIMARY KEY,
 SUBMISSION_ID VARCHAR2(128 CHAR) CONSTRAINT STL_NN_SF_SUBMISSION NOT NULL,
 INVOICE_ID VARCHAR2(128 CHAR) CONSTRAINT STL_NN_SF_INVOICE NOT NULL,
 STAGE NUMBER(1) CONSTRAINT STL_NN_SF_STAGE NOT NULL,
 EVENT VARCHAR2(8 CHAR) CONSTRAINT STL_NN_SF_EVENT NOT NULL,
 AMOUNT_SEN NUMBER(10) CONSTRAINT STL_NN_SF_SEN NOT NULL,
 CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP CONSTRAINT STL_NN_SF_CREATED NOT NULL,
 CONSTRAINT STL_FK_SF_SUBMISSION FOREIGN KEY (SUBMISSION_ID) REFERENCES STL_SYNTHETIC_SUBMISSIONS (ID),
 CONSTRAINT STL_UK_SF_STAGE UNIQUE (SUBMISSION_ID,STAGE,EVENT),
 CONSTRAINT STL_UK_SF_INVOICE UNIQUE (INVOICE_ID,EVENT),
 CONSTRAINT STL_CK_SF_STAGE CHECK (STAGE IN (1,2)),
 CONSTRAINT STL_CK_SF_EVENT CHECK (EVENT IN ('INVOICE','RECEIPT')),
 CONSTRAINT STL_CK_SF_SEN CHECK (AMOUNT_SEN BETWEEN 1 AND 2147483647)
)
-- @statement
CREATE TRIGGER STL_TR_SF_APPEND_ONLY
 BEFORE UPDATE OR DELETE ON STL_SYNTH_FINANCIAL_ENTRIES
BEGIN
 RAISE_APPLICATION_ERROR(-20008,'Synthetic financial entries are append-only');
END;
